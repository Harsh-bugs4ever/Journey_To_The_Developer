public class Floop {
    public static void main(String args[]){
       // for decrement 
       for (int i=4;i>=1;i--)
       {
            System.out.println("hii " + i);
       }
       //Increment
       for(int i = 0;i<=4;i++)
       {
            System.out.println("hii " + i );
       }
       //So when you are using 0 u need to stop 1 time less so it can print that much statemnet
    }
    
}
